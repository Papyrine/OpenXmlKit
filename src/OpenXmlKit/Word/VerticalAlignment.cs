namespace OpenXmlKit.Word;

/// <summary>
/// Where content sits within the height of a table cell.
/// </summary>
public enum VerticalAlignment
{
    /// <summary>
    /// Content sits at the top of the cell.
    /// </summary>
    Top,

    /// <summary>
    /// Content is centred vertically.
    /// </summary>
    Center,

    /// <summary>
    /// Content sits at the bottom.
    /// </summary>
    Bottom
}
